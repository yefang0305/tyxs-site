水之属性为“润下”，代表着寒凉、滋润与闭藏。在人体中，水对应着先天之本——肾脏与膀胱系统，主宰着骨骼的生长与骨髓的充盈，其荣华表现在头发的乌黑与浓密。
八字中水气干枯或水势泛滥成灾，皆深刻预示着个体的生殖系统功能低下、泌尿系统疾病、内分泌失调以及整体免疫力与生命元气的提前衰退。
